                                 function(x,z){
                                     c(all(x>0),all(z%in%x))},
                                 z=sz_defn[[ii]])
            }
            stopifnot("Missing sz parameters" = all(z[,2]),
                      "Negative or missing sz parameter values" = all(z[,1]))
            private$model <- mdl
